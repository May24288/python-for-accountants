# -*- coding: utf-8 -*-
"""
案例 04｜会计凭证断号 / 重复号 / 异常检查
=============================================
场景：凭证是最基础的东西，但恰恰最容易出问题：
        · 断号：中间某个号没了（凭证被抽走或漏记）
        · 重号：同一个凭证号被用了两次
        · 日期倒挂：8 月的凭证制单日期写成了 6 月
        · 金额异常：突然出现一笔特别大的

审计来查或者自己月底自查，这几项是必看的。
手工查：几百张凭证翻一遍，不现实。
用脚本：一秒扫完，问题清单直接列出来。

运行：
    python 凭证检查.py
"""

import os

import pandas as pd

当前目录 = os.path.dirname(os.path.abspath(__file__))
数据目录 = os.path.dirname(当前目录)
数据路径 = os.path.join(数据目录, "示例数据", "会计凭证清单.csv")

# ---------- 1. 读凭证清单 ----------
凭证 = pd.read_csv(数据路径, encoding="utf-8-sig")
凭证["制单日期"] = pd.to_datetime(凭证["制单日期"])
# 从"记-0001"这种字号里把纯数字抠出来
凭证["凭证号"] = 凭证["凭证字号"].str.extract(r"(\d+)").astype(int)
凭证["月份"] = 凭证["制单日期"].dt.month

print(f"共读入 {len(凭证)} 张凭证，覆盖月份：{sorted(凭证['月份'].unique())}\n")

问题清单 = []

# ---------- 2. 检查一：重号 ----------
重复 = 凭证[凭证.duplicated(subset=["月份", "凭证号"], keep=False)]
if len(重复) > 0:
    for (月, 号), 组 in 重复.groupby(["月份", "凭证号"]):
        问题清单.append({
            "问题类型": "① 凭证重号",
            "月份": f"{月}月",
            "凭证字号": f"记-{号:04d}",
            "说明": f"这个号出现了 {len(组)} 次，制单人分别是：{'、'.join(组['制单人'].tolist())}",
        })
    print(f"① 发现重号 {重复.groupby(['月份', '凭证号']).ngroups} 组")
else:
    print("① 没发现重号 ✓")

# ---------- 3. 检查二：断号 ----------
断号数量 = 0
for 月, 组 in 凭证.groupby("月份"):
    已有号 = set(组["凭证号"])
    最小号, 最大号 = min(已有号), max(已有号)
    缺失号 = sorted(set(range(最小号, 最大号 + 1)) - 已有号)
    if 缺失号:
        断号数量 += len(缺失号)
        问题清单.append({
            "问题类型": "② 凭证断号",
            "月份": f"{月}月",
            "凭证字号": "、".join(f"记-{n:04d}" for n in 缺失号),
            "说明": f"编号区间 {最小号}-{最大号} 中缺了 {len(缺失号)} 个号",
        })
if 断号数量:
    print(f"② 发现断号 {断号数量} 个")
else:
    print("② 没发现断号 ✓")

# ---------- 4. 检查三：制单日期与凭证号顺序倒挂 ----------
倒挂 = []
for 月, 组 in 凭证.groupby("月份"):
    排序后 = 组.sort_values("凭证号")
    # 正常情况：凭证号越大，制单日期应该越晚
    时间差 = 排序后["制单日期"].diff().dt.days
    异常位置 = 时间差[时间差 < -3]
    for 位置 in 异常位置.index:
        倒挂.append({
            "问题类型": "③ 日期倒挂",
            "月份": f"{月}月",
            "凭证字号": 排序后.loc[位置, "凭证字号"],
            "说明": f"制单日期 {排序后.loc[位置, '制单日期'].strftime('%Y-%m-%d')}，比前一张凭证早了很久",
        })
问题清单.extend(倒挂)
print(f"③ 发现日期倒挂 {len(倒挂)} 张")

# ---------- 5. 检查四：金额异常值 ----------
均值 = 凭证["金额"].mean()
标准差 = 凭证["金额"].std()
阈值 = 均值 + 3 * 标准差
大额 = 凭证[凭证["金额"] > 阈值]
for _, 行 in 大额.iterrows():
    问题清单.append({
        "问题类型": "④ 金额异常偏大",
        "月份": f"{行['月份']}月",
        "凭证字号": 行["凭证字号"],
        "说明": f"金额 {行['金额']:,.2f} 元，远超平均（平均 {均值:,.2f} 元），建议复核原始单据",
    })
print(f"④ 发现金额异常偏大 {len(大额)} 张（阈值 {阈值:,.2f} 元）")

# ---------- 6. 检查五：同一张凭证出现多次但金额不同 ----------
# 注意：凭证号是每个月各自从 1 开始编的，所以要按"月份+字号"一起分组，
# 否则 6 月的记-0001 和 7 月的记-0001 会被误判成同一张。
同名不同额 = 凭证.groupby(["月份", "凭证字号"])["金额"].nunique()
可疑字号 = 同名不同额[同名不同额 > 1]
for (月, 字号) in 可疑字号.index:
    问题清单.append({
        "问题类型": "⑤ 同号不同金额",
        "月份": f"{月}月",
        "凭证字号": 字号,
        "说明": "同一个凭证字号对应了多个不同金额，可能是录入错误",
    })
print(f"⑤ 发现同号不同金额 {len(可疑字号)} 个")

# ---------- 7. 汇总输出 ----------
print("\n" + "=" * 60)
if 问题清单:
    问题表 = pd.DataFrame(问题清单).sort_values(["问题类型", "月份"])
    print(f"检查完毕，一共发现 {len(问题表)} 条问题：\n")
    print(问题表.to_string(index=False))

    输出目录 = os.path.join(当前目录, "输出")
    os.makedirs(输出目录, exist_ok=True)
    输出路径 = os.path.join(输出目录, "凭证检查问题清单.xlsx")
    问题表.to_excel(输出路径, index=False)
    print(f"\n问题清单已保存到：{输出路径}")
else:
    print("检查完毕，没发现任何问题 ✓")

# ---------- 8. 顺手统计一下整体情况 ----------
print("\n--- 凭证整体情况 ---")
统计 = 凭证.groupby("月份").agg(
    凭证张数=("凭证字号", "count"),
    金额合计=("金额", "sum"),
    最早日期=("制单日期", "min"),
    最晚日期=("制单日期", "max"),
)
统计["金额合计"] = 统计["金额合计"].round(2)
print(统计.to_string())
