# -*- coding: utf-8 -*-
"""
一键生成示例数据
---------------------------------------------
这个脚本会生成本仓库 4 个案例需要用到的全部示例数据。
数据全部是虚构的，随便用、随便改，不涉及任何真实公司信息。

运行方法：在本文件所在文件夹打开命令行，输入
    python 一键生成示例数据.py
然后回车。

说明：本脚本只用到 Python 自带功能，不需要装任何额外的库。
"""

import csv
import os
import random
from datetime import date, timedelta

# 固定随机数种子：保证每次生成的数据一模一样，方便对照教程结果
random.seed(20260808)

# 当前文件所在目录
根目录 = os.path.dirname(os.path.abspath(__file__))
数据目录 = os.path.join(根目录, "示例数据")
os.makedirs(数据目录, exist_ok=True)


def 写csv(文件路径, 表头, 行列表):
    with open(文件路径, "w", newline="", encoding="utf-8-sig") as f:
        writer = csv.writer(f)
        writer.writerow(表头)
        writer.writerows(行列表)
    print(f"  已生成：{os.path.relpath(文件路径, 根目录)}  （{len(行列表)} 行）")


# ============ 案例 1：多子公司批量并表 ============
print("【案例1】生成 12 家子公司月度报表 ...")

科目列表 = [
    ("1001", "库存现金"),
    ("1002", "银行存款"),
    ("1122", "应收账款"),
    ("1405", "库存商品"),
    ("1601", "固定资产"),
    ("2202", "应付账款"),
    ("6001", "主营业务收入"),
    ("6401", "主营业务成本"),
    ("6601", "销售费用"),
    ("6602", "管理费用"),
]

子公司列表 = [
    "杭州总部", "宁波分公司", "温州分公司", "台州分公司",
    "金华分公司", "绍兴分公司", "嘉兴分公司", "湖州分公司",
    "丽水分公司", "衢州分公司", "舟山分公司", "义乌分公司",
]

for 公司 in 子公司列表:
    行列表 = []
    for 科目代码, 科目名称 in 科目列表:
        # 资产/负债类科目给余额，收入/成本类科目给发生额
        if 科目代码.startswith("6"):
            本期金额 = round(random.uniform(80000, 900000), 2)
        else:
            本期金额 = round(random.uniform(200000, 3500000), 2)
        行列表.append([
            "2026-08",          # 会计期间
            公司,               # 公司
            科目代码,           # 科目代码
            科目名称,           # 科目名称
            本期金额,           # 本期金额
            "借" if 科目代码[0] in "16" else "贷",  # 借贷方向
        ])
    # 故意埋两个坑：一家公司少一行、一家公司科目名称写法不一致
    if 公司 == "温州分公司":
        行列表 = 行列表[:-1]          # 少记一行，模拟漏报
    if 公司 == "义乌分公司":
        行列表[6][3] = "主营业务收入 "  # 名称后面多了空格，模拟脏数据

    文件路径 = os.path.join(数据目录, f"子公司报表_{公司}.csv")
    写csv(文件路径, ["会计期间", "公司", "科目代码", "科目名称", "本期金额", "借贷方向"], 行列表)


# ============ 案例 2：往来账龄分析 ============
print("【案例2】生成应收账款明细 ...")

客户列表 = [
    "永康市××工具有限公司", "玉环县××机械厂", "启东市××电动工具厂",
    "余姚市××塑料制品厂", "慈溪市××电器有限公司", "温岭市××机电有限公司",
    "佛山市××五金厂", "东莞市××精密制造有限公司", "苏州市××工业设备有限公司",
    "潍坊市××动力机械有限公司", "临沂市××磨料磨具有限公司", "常州市××齿轮有限公司",
]

今天 = date(2026, 8, 31)
行列表 = []
单据号 = 1
for 客户 in 客户列表:
    for _ in range(random.randint(4, 9)):
        开票日 = 今天 - timedelta(days=random.randint(1, 200))
        金额 = round(random.uniform(15000, 480000), 2)
        # 30% 的单据已经收款，用来演示已清账的部分要剔除
        已收金额 = 金额 if random.random() < 0.3 else round(random.uniform(0, 金额 * 0.6), 2)
        行列表.append([
            f"AR-2026-{单据号:04d}",
            客户,
            开票日.strftime("%Y-%m-%d"),
            f"XS-{random.randint(10000, 99999)}",
            金额,
            已收金额,
            "是" if random.random() < 0.15 else "否",   # 是否争议中
        ])
        单据号 += 1

写csv(
    os.path.join(数据目录, "应收账款明细.csv"),
    ["单据编号", "客户名称", "开票日期", "销售单号", "应收金额", "已收金额", "是否争议"],
    行列表,
)


# ============ 案例 3：发票台账 vs 银行流水 自动对账 ============
print("【案例3】生成发票台账与银行流水 ...")

往来单位列表 = 客户列表[:8]

# --- 发票台账（我方开出发票）---
发票行 = []
发票号 = 1
for 单位 in 往来单位列表:
    for _ in range(random.randint(3, 7)):
        开票日 = 今天 - timedelta(days=random.randint(5, 90))
        金额 = round(random.uniform(20000, 320000), 2)
        发票行.append([
            f"发票{发票号:04d}",
            开票日.strftime("%Y-%m-%d"),
            单位,
            金额,
        ])
        发票号 += 1

# --- 银行流水（实际到账）---
# 规则：90% 的发票能正常对上；5% 金额差几块钱（手续费）；5% 银行有账但发票没有
流水行 = []
流水号 = 1
for 行 in 发票行:
    r = random.random()
    if r < 0.90:
        # 正常到账
        流水行.append([f"流水{流水号:04d}", 行[1], 行[2], 行[3], f"发票{行[0][2:]}"])
        流水号 += 1
    elif r < 0.95:
        # 到账金额少了手续费
        流水行.append([f"流水{流水号:04d}", 行[1], 行[2], round(行[3] - random.uniform(3, 30), 2), f"发票{行[0][2:]}"])
        流水号 += 1
    else:
        # 完全没到账（挂账）
        pass

# 补两笔银行有、发票没有的（预收款 / 无票收入）
流水行.append([f"流水{流水号:04d}", "2026-08-12", "永康市××工具有限公司", 58000.00, ""])
流水行.append([f"流水{流水号+1:04d}", "2026-08-20", "佛山市××五金厂", 12600.00, ""])

写csv(os.path.join(数据目录, "发票台账.csv"), ["发票号码", "开票日期", "客户名称", "价税合计"], 发票行)
写csv(os.path.join(数据目录, "银行流水.csv"), ["流水号", "到账日期", "付款方", "到账金额", "备注发票号"], 流水行)


# ============ 案例 4：会计凭证断号 / 重复号检查 ============
print("【案例4】生成会计凭证清单 ...")

凭证行 = []
凭证号 = 1
for 月份 in [6, 7, 8]:
    当月凭证数 = random.randint(60, 80)
    当月编号列表 = list(range(1, 当月凭证数 + 1))
    # 模拟 2 个断号（凭证被作废抽走）
    for _ in range(2):
        if len(当月编号列表) > 5:
            当月编号列表.remove(random.choice(当月编号列表[1:-1]))
    # 模拟 1 个重复号（同一个号被用了两次）
    if 当月编号列表:
        重复号 = random.choice(当月编号列表[1:-1])
        当月编号列表.append(重复号)

    # 先按凭证号的顺序排出一串递增的日期，再打乱编号顺序，
    # 这样绝大部分凭证是"号越大日期越晚"，只有个别是真正的时间倒挂
    # 同一个月里日期可以重复（一天做多张凭证很正常），所以用 choices 而不是 sample
    当月最后一天 = 28
    递增日期 = sorted(random.choices(range(1, 当月最后一天 + 1), k=len(当月编号列表)))
    打乱顺序 = 当月编号列表[:]
    # 人为制造 1 例真正的时间倒挂：把某个中间号塞到最前面
    if len(打乱顺序) > 10:
        倒挂号 = 打乱顺序.pop(len(打乱顺序) // 2)
        打乱顺序.insert(1, 倒挂号)

    for 序号, 编号 in enumerate(打乱顺序):
        凭证行.append([
            f"记-{编号:04d}",
            f"2026-{月份:02d}-{递增日期[序号]:02d}",
            random.choice(["收款凭证", "付款凭证", "转账凭证"]),
            random.choice(["张三", "李四", "王五", "赵六"]),
            round(random.uniform(1000, 900000), 2),
        ])

写csv(
    os.path.join(数据目录, "会计凭证清单.csv"),
    ["凭证字号", "制单日期", "凭证类型", "制单人", "金额"],
    凭证行,
)

print("\n全部示例数据生成完毕！可以去 示例数据 文件夹里看看。")
